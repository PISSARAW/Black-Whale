export type PostcardStampCategory = 'official' | 'royal' | 'underworld' | 'expedition'
export type PostcardStampShape = 'round' | 'oval' | 'square' | 'ticket' | 'diamond'
export type PostcardStampTone =
  'formal' | 'military' | 'clinical' | 'ominous' | 'luxe' | 'playful' | 'gentle' | 'clandestine'

export interface PostcardStampDefinition {
  id: string
  category: PostcardStampCategory
  mark: string
  ink: string
  shape: PostcardStampShape
  tone: PostcardStampTone
  rotation: number
}

