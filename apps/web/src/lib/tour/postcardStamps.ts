export type PostcardStampId = (typeof POSTCARD_STAMPS)[number]['id']

export function postcardStamp(id: PostcardStampId): (typeof POSTCARD_STAMPS)[number] {
  return POSTCARD_STAMPS.find((stamp) => stamp.id === id) ?? POSTCARD_STAMPS[0]
}
