import { readFileSync, writeFileSync, readdirSync } from 'node:fs'

// Compact browser catalogue, derived from the same facts as the character archive.
const directory = new URL('../apps/web/src/lib/fighting/', import.meta.url)
const characters = JSON.parse(
  readFileSync(new URL('../data/characters/characters.json', import.meta.url)),
)
const abilities = JSON.parse(
  readFileSync(new URL('../data/abilities/abilities.json', import.meta.url)),
)
const aliases = {
  enhancement: 'enhancer',
  emission: 'emitter',
  transmutation: 'transmuter',
  conjuration: 'conjurer',
  manipulation: 'manipulator',
  specialization: 'specialist',
}
const categories = new Set([
  'enhancer',
  'emitter',
  'transmuter',
  'conjurer',
  'manipulator',
  'specialist',
])
const category = (value) =>
  categories.has(aliases[value] ?? value) ? (aliases[value] ?? value) : 'unknown'
const profiles = {}
for (const name of readdirSync(directory).filter((name) => /^roster.*\.ts$/.test(name))) {
  const source = readFileSync(new URL(name, directory), 'utf8')
  for (const [, id, modelId] of source.matchAll(/id: '([^']+)',\s*modelId: '([^']+)'/g)) {
    const character = characters.find((entry) => entry.id === modelId)
    profiles[id] = {
      affinity: category(character?.nen?.type),
      abilities: abilities
        .filter((ability) => ability.ownerId === modelId)
        .map((ability) => ability.id),
    }
  }
}
const abilityCategories = Object.fromEntries(
  abilities.map((ability) => [
    ability.id,
    [
      ...new Set(
        [ability.category, ...(ability.secondaryCategories ?? [])]
          .map(category)
          .filter((value) => value !== 'unknown'),
      ),
    ],
  ]),
)
const entries = (values) =>
  Object.entries(values)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
    .join('\n')
writeFileSync(
  new URL('nenCatalogue.gen.ts', directory),
  `// Generated by node scripts/generate-fighting-nen.mjs from data/. Do not edit.\nimport type { NenCategory } from '@black-whale/domain'\nimport type { ActiveNenCategory } from '@black-whale/nen-engine'\n\nexport const FIGHT_NEN_PROFILES: Readonly<Record<string, { affinity: NenCategory; abilities: readonly string[] }>> = {\n${entries(profiles)}\n}\n\nexport const FIGHT_ABILITY_CATEGORIES: Readonly<Record<string, readonly ActiveNenCategory[]>> = {\n${entries(abilityCategories)}\n}\n`,
)
